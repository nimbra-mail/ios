/// The line under Inbox zero's headline: a new one each day, through a year of them, as
/// on the Mac (its `inspiration.rs`, line for line). Some quiet, some silly, some borrowed
/// from people who said it first: a quote has its author after it, shown apart below.
nonisolated enum DailyLine {
    /// The day's line, localized, and a quote's author apart.
    static func line(for date: Date, calendar: Calendar = .current) -> (line: String, author: String?) {
        split(String(localized: lines[index(for: date, calendar: calendar)]))
    }

    /// Which line a day has: the Mac's, its days since the start of the common era (as
    /// chrono counts them, on the Gregorian calendar in the local time zone) round the
    /// year of lines. As 365 is not a multiple of seven, a line lands on another weekday
    /// each year.
    static func index(for date: Date, calendar: Calendar = .current) -> Int {
        var gregorian = Calendar(identifier: .gregorian)
        gregorian.timeZone = calendar.timeZone
        let day = gregorian.dateComponents([.year, .month, .day], from: date)
        let days = daysFromCommonEra(year: day.year ?? 1970, month: day.month ?? 1, day: day.day ?? 1)
        return ((days % lines.count) + lines.count) % lines.count
    }

    /// Days from 0001-01-01 (day 1) on the proleptic Gregorian calendar, as chrono's
    /// `num_days_from_ce` counts them (Howard Hinnant's `days_from_civil`, from 1970).
    static func daysFromCommonEra(year: Int, month: Int, day: Int) -> Int {
        let y = month <= 2 ? year - 1 : year
        let era = (y >= 0 ? y : y - 399) / 400
        let yoe = y - era * 400
        let doy = (153 * (month + (month > 2 ? -3 : 9)) + 2) / 5 + day - 1
        let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy
        return era * 146_097 + doe - 719_468 + 719_163
    }

    /// A quote and its author apart: “Less is more.” Mies is (“Less is more.”, Mies). Any
    /// other line is itself, with no author.
    static func split(_ line: String) -> (line: String, author: String?) {
        guard line.hasPrefix("“"), let end = line.lastIndex(of: "”") else { return (line, nil) }
        let quote = String(line[...end])
        let author = line[line.index(after: end)...].trimmingCharacters(in: .whitespaces)
        return author.isEmpty ? (line, nil) : (quote, author)
    }

